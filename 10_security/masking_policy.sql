USE ROLE ACCOUNTADMIN;
USE DATABASE RETAIL_SUPPLY_CHAIN;

-- Masking policies are an Enterprise Edition feature.
CREATE OR REPLACE MASKING POLICY GOLD.MASK_CUSTOMER_EMAIL
AS (val STRING)
RETURNS STRING ->
  CASE
    WHEN CURRENT_ROLE() IN ('DATA_ENGINEER', 'ACCOUNTADMIN')
      THEN val
    ELSE '***MASKED***'
  END;

ALTER TABLE GOLD.DIM_CUSTOMER
  MODIFY COLUMN email
  SET MASKING POLICY GOLD.MASK_CUSTOMER_EMAIL;

