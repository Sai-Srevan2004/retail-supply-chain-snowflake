-- Run role administration as ACCOUNTADMIN (or an equivalent security-admin role).
-- Object ownership/grants can be adjusted to match your Snowflake account policy.

USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS DATA_ENGINEER;
CREATE ROLE IF NOT EXISTS DATA_ANALYST;
CREATE ROLE IF NOT EXISTS DATA_VIEWER;

GRANT USAGE ON WAREHOUSE RETAIL_WH TO ROLE DATA_ENGINEER;
GRANT USAGE ON WAREHOUSE RETAIL_WH TO ROLE DATA_ANALYST;
GRANT USAGE ON WAREHOUSE RETAIL_WH TO ROLE DATA_VIEWER;

GRANT USAGE ON DATABASE RETAIL_SUPPLY_CHAIN TO ROLE DATA_ENGINEER;
GRANT USAGE ON DATABASE RETAIL_SUPPLY_CHAIN TO ROLE DATA_ANALYST;
GRANT USAGE ON DATABASE RETAIL_SUPPLY_CHAIN TO ROLE DATA_VIEWER;

GRANT USAGE ON SCHEMA RETAIL_SUPPLY_CHAIN.RAW TO ROLE DATA_ENGINEER;
GRANT USAGE ON SCHEMA RETAIL_SUPPLY_CHAIN.SILVER TO ROLE DATA_ENGINEER;
GRANT USAGE ON SCHEMA RETAIL_SUPPLY_CHAIN.GOLD TO ROLE DATA_ENGINEER;

GRANT USAGE ON SCHEMA RETAIL_SUPPLY_CHAIN.GOLD TO ROLE DATA_ANALYST;
GRANT SELECT ON ALL TABLES IN SCHEMA RETAIL_SUPPLY_CHAIN.GOLD TO ROLE DATA_ANALYST;
GRANT SELECT ON FUTURE TABLES IN SCHEMA RETAIL_SUPPLY_CHAIN.GOLD TO ROLE DATA_ANALYST;
GRANT SELECT ON DYNAMIC TABLE RETAIL_SUPPLY_CHAIN.GOLD.DAILY_SALES_SUMMARY TO ROLE DATA_ANALYST;

GRANT USAGE ON SCHEMA RETAIL_SUPPLY_CHAIN.GOLD TO ROLE DATA_VIEWER;
GRANT SELECT ON GOLD.DIM_PRODUCT TO ROLE DATA_VIEWER;
GRANT SELECT ON GOLD.DIM_STORE TO ROLE DATA_VIEWER;
GRANT SELECT ON GOLD.DIM_DATE TO ROLE DATA_VIEWER;
GRANT SELECT ON GOLD.FACT_SALES TO ROLE DATA_VIEWER;
GRANT SELECT ON DYNAMIC TABLE GOLD.DAILY_SALES_SUMMARY TO ROLE DATA_VIEWER;

-- DATA_ANALYST is intentionally not granted direct access to DIM_CUSTOMER here;
-- the masking policy file demonstrates controlled email access separately.

