USE DATABASE RETAIL_SUPPLY_CHAIN;

SELECT 'CUSTOMERS' entity, COUNT(*), COUNT(DISTINCT _source_file) files,
       COUNT(DISTINCT _batch_id) batches FROM RAW.CUSTOMERS
UNION ALL
SELECT 'PRODUCTS', COUNT(*), COUNT(DISTINCT _source_file), COUNT(DISTINCT _batch_id) FROM RAW.PRODUCTS
UNION ALL
SELECT 'STORES', COUNT(*), COUNT(DISTINCT _source_file), COUNT(DISTINCT _batch_id) FROM RAW.STORES
UNION ALL
SELECT 'SALES', COUNT(*), COUNT(DISTINCT _source_file), COUNT(DISTINCT _batch_id) FROM RAW.SALES;

-- Expected initial row counts:
-- CUSTOMERS 1000, PRODUCTS 100, STORES 30, SALES 10000.
